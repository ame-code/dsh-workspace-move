/**
 * Build the Client half into the single browser factory the Host serves.
 *
 * The Client module system materialises a package's `exports["./client"]` file as
 * `factory(require)`, so that file must already be a wrapped bundle: a bare ES
 * module there fails in the browser with "Cannot use import statement outside a
 * module" and takes the whole Web boot down with it. The source therefore lives
 * in `src/client.js` and this script writes the bundle to `lib/client.js`.
 *
 * `react` stays external because the browser seed table provides it.
 * @module @reed-io/dsh-workspace-move/scripts
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, "src", "client.js");
const target = join(root, "lib", "client.js");

/**
 * Load esbuild: the local install when present, otherwise the scratch toolchain
 * recorded under `.refs` beside this repository.
 * @returns the esbuild module.
 */
async function loadEsbuild() {
  const local = await import("esbuild").catch(() => undefined);
  if (local !== undefined) return local;
  const scratch = join(root, ".refs", "tools", "esbuild");
  const url = new URL(`file://${scratch.replaceAll("\\", "/")}/node_modules/esbuild/lib/main.js`);
  return (await import(url.href)).default;
}

const esbuild = await loadEsbuild();
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
const built = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["chrome110"],
  jsx: "transform",
  jsxFactory: "h",
  external: ["react", "react/jsx-runtime"],
  legalComments: "none"
});
const code = built.outputFiles[0].text;
const wrapped = `/* ${pkg.name} — generated by scripts/build-client.mjs from src/client.js; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: function (require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`;
await mkdir(dirname(target), { recursive: true });
await writeFile(target, wrapped, "utf8");
// stderr: prepack runs during `npm pack --json`, and anything on stdout would
// corrupt the JSON that callers parse.
console.error(`built ${target} (${Buffer.byteLength(wrapped)} bytes)`);
